-- One colour per completion kind, expanded for every plugin that draws
-- kind icons. Four hues: functions, types, values, text; variables stay fg.
local function kinds(c)
  return {
    Function = c.func, Method = c.func, Constructor = c.func,
    Class = c.type, Interface = c.type, Struct = c.type, Enum = c.type, Module = c.type,
    Namespace = c.type, Package = c.type, TypeParameter = c.type, Event = c.type,
    File = c.type, Folder = c.type,
    Constant = c.num, EnumMember = c.num, Number = c.num, Boolean = c.num, Value = c.num,
    Unit = c.num, Null = c.num, Color = c.num,
    Text = c.str, Snippet = c.str, String = c.str, Reference = c.str,
    Keyword = c.keyword, Operator = c.keyword,
    Variable = c.fg, Field = c.fg, Property = c.fg, Key = c.fg, Object = c.fg, Array = c.fg,
    Copilot = c.info, Codeium = c.info, TabNine = c.info, Supermaven = c.info,
  }
end

